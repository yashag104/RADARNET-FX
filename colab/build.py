#!/usr/bin/env python3
"""
build.py — bundle a Colab step script into ONE self-contained file
==================================================================
Embeds the project files a step needs (code + trained checkpoint) as base64
so the user uploads a single .py to Colab and runs it with `%run`.

    python colab/build.py step1      →  colab/radarnet_step1.py
    python colab/build.py all        →  every step
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

STEPS = {
    "step1": {
        "main": "colab/step1_main.py",
        "files": ["python/model.py", "python/quantize.py", "python/int_quant.py",
                  "python/preprocess.py", "checkpoints/radarnet_best.pth",
                  "checkpoints/metrics.json"],
    },
    "step2": {
        "main": "colab/step2_main.py",
        "files": ["python/model.py", "python/quantize.py", "python/int_quant.py",
                  "python/anomaly_dataset.py", "python/anom_eval.py",
                  "python/train_anomaly.py", "python/baselines.py",
                  "python/anom_report.py"],
    },
}


def build(step):
    cfg = STEPS[step]
    files = {}
    for rel in cfg["files"]:
        with open(os.path.join(ROOT, rel), "rb") as f:
            files[rel] = base64.b64encode(f.read()).decode()
    with open(os.path.join(ROOT, "checkpoints", "metrics.json")) as f:
        expected = 100 * json.load(f)["test_acc"]
    with open(os.path.join(ROOT, "colab", "common.py")) as f:
        common = f.read()
    with open(os.path.join(ROOT, cfg["main"])) as f:
        main = f.read()

    out = os.path.join(ROOT, "colab", f"radarnet_{step}.py")
    with open(out, "w") as f:
        f.write(f"# radarnet_{step}.py — GENERATED by colab/build.py, do not edit.\n")
        f.write("# Upload this one file to Colab and run:  %run radarnet_" + step + ".py\n")
        f.write(f"EXPECTED_FP32_ACC = {expected:.4f}\n")
        f.write("EMBEDDED_FILES = {\n")
        for rel, b64 in files.items():
            f.write(f"    {rel!r}: (\n")
            for i in range(0, len(b64), 100):
                f.write(f"        {b64[i:i + 100]!r}\n")
            f.write("    ),\n")
        f.write("}\n\n")
        f.write(common + "\n\n")
        f.write(main)
    print(f"{out}  ({os.path.getsize(out) / 1024:.0f} KB, {len(files)} embedded files)")


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "all"
    for st in (STEPS if arg == "all" else [arg]):
        build(st)
